/**
 * mcAI dashboard.
 *
 * No framework, no build step: the daemon serves three static files. State
 * arrives over Server-Sent Events, which the browser reconnects on its own, so
 * restarting the daemon does not require reloading the page.
 */

const $ = (id) => document.getElementById(id);
const TOKEN = new URLSearchParams(location.search).get('token');

const api = (path, opts = {}) => {
  const headers = { 'content-type': 'application/json', ...(opts.headers || {}) };
  if (TOKEN) headers['x-mcai-token'] = TOKEN;
  return fetch(path, { ...opts, headers });
};

const fmt = (n) => (typeof n === 'number' ? n.toLocaleString('en-US') : '—');
const time = (t) => new Date(t).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });

let lastState = null;
let busy = false;

// ── Status pills ──────────────────────────────────────────────────────────

function renderPills(state) {
  const s = state.status || {};
  const pills = [
    pill('bot', s.bot?.connected, s.bot?.connected ? `${s.bot.username} @ ${(s.bot.position || []).join(', ')}` : 'offline'),
    pill('rcon', s.rcon?.connected, s.rcon?.connected ? `${s.rcon.avgLatencyMs ?? 0}ms avg` : 'offline'),
    pill('model', !!state.llm, state.llm ? state.llm.model : 'prefabs only'),
    pill('players', (s.bot?.players || []).length > 0, `${(s.bot?.players || []).length} online`),
  ];
  $('pills').innerHTML = pills.join('');
}

function pill(label, on, detail) {
  const cls = on === undefined ? '' : on ? 'on' : 'off';
  return `<span class="pill ${cls}"><span class="dot"></span>${label}<span style="opacity:.6">${escapeHtml(detail || '')}</span></span>`;
}

// ── Live panel ────────────────────────────────────────────────────────────

function renderLive(state) {
  const job = state.current;
  busy = !!job;
  $('build-btn').disabled = busy;
  $('cancel-btn').disabled = !busy;
  $('undo-btn').disabled = busy || !state.undoDepth;

  if (!job) {
    const last = (state.history || []).at(-1);
    $('live-title').textContent = last ? `Last: ${last.prompt}` : 'Idle';
    $('live-phase').textContent = last ? last.status : 'waiting for a request';
    $('progress').style.width = last ? '100%' : '0';
    if (last) setMetrics(last);
    if (last?.previewSvg) showPreview(last.previewSvg);
    return;
  }

  $('live-title').textContent = job.prompt;
  $('live-phase').textContent = job.phase;
  $('progress').style.width = `${Math.round((job.progress || 0) * 100)}%`;
  setMetrics(job);
}

function setMetrics(job) {
  $('m-blocks').textContent = fmt(job.blocks);
  $('m-commands').textContent = fmt(job.commands);
  $('m-ratio').textContent = job.commands ? (job.blocks / job.commands).toFixed(1) : '—';
  const tokens = (job.tokensIn || 0) + (job.tokensOut || 0);
  $('m-tokens').textContent = tokens ? fmt(tokens) : '0';
  $('m-cost').textContent = `$${(job.costUsd || 0).toFixed(4)}`;
  const ms = (job.finishedAt || Date.now()) - (job.startedAt || Date.now());
  $('m-time').textContent = `${(Math.max(0, ms) / 1000).toFixed(1)}s`;
}

function showPreview(svg) {
  const box = $('preview');
  box.innerHTML = '';
  // The SVG is generated by our own compiler, but it is still injected markup:
  // parse it and take only the root element rather than trusting a string.
  const doc = new DOMParser().parseFromString(svg, 'image/svg+xml');
  const root = doc.documentElement;
  if (!root || root.nodeName === 'parsererror') {
    box.innerHTML = '<p class="empty">Preview unavailable.</p>';
    return;
  }
  box.appendChild(document.importNode(root, true));
}

// ── Log ───────────────────────────────────────────────────────────────────

function addLog(entry) {
  const list = $('log');
  const li = document.createElement('li');
  li.className = entry.level || 'info';
  li.innerHTML = `<span class="t">${time(entry.t)}</span>${escapeHtml(entry.msg)}`;
  list.prepend(li);
  while (list.children.length > 120) list.lastChild.remove();
}

// ── History ───────────────────────────────────────────────────────────────

function renderHistory(state) {
  const body = $('history-body');
  const rows = (state.history || []).slice().reverse();
  if (rows.length === 0) {
    body.innerHTML = '<tr class="empty-row"><td colspan="7">Nothing built yet.</td></tr>';
    return;
  }
  body.innerHTML = rows.map((j) => `
    <tr>
      <td>${time(j.finishedAt || j.createdAt)}</td>
      <td>${escapeHtml(j.prompt)}</td>
      <td class="num">${fmt(j.blocks)}</td>
      <td class="num">${fmt(j.commands)}</td>
      <td class="num">${fmt((j.tokensIn || 0) + (j.tokensOut || 0))}</td>
      <td class="num">$${(j.costUsd || 0).toFixed(4)}</td>
      <td><span class="status ${j.status}">${j.status}</span></td>
    </tr>`).join('');
}

// ── Library ───────────────────────────────────────────────────────────────

async function renderLibrary() {
  const res = await api('/api/prefabs');
  const { prefabs } = await res.json();
  const gallery = $('gallery');
  gallery.innerHTML = prefabs.map((p) => `
    <button class="card" data-prefab="${escapeAttr(p.name)}" title="${escapeAttr(p.summary)}">
      <span class="thumb"><img loading="lazy" alt="" src="/api/preview/${encodeURIComponent(p.name)}.svg?scale=3${TOKEN ? `&token=${encodeURIComponent(TOKEN)}` : ''}"></span>
      <span class="label">${escapeHtml(p.name)}</span>
      <span class="summary">${escapeHtml(p.summary)}</span>
    </button>`).join('');

  gallery.addEventListener('click', async (e) => {
    const card = e.target.closest('[data-prefab]');
    if (!card || busy) return;
    await submit(card.dataset.prefab);
  });
}

async function renderStyles() {
  const res = await api('/api/styles');
  const { styles } = await res.json();
  const select = $('style');
  for (const s of styles) {
    const opt = document.createElement('option');
    opt.value = s.name;
    opt.textContent = `${s.name} — ${s.description.slice(0, 48)}`;
    select.appendChild(opt);
  }
  select.addEventListener('change', async () => {
    await api('/api/style', { method: 'POST', body: JSON.stringify({ style: select.value || null }) });
    toast(select.value ? `Style: ${select.value}` : 'Style: automatic');
  });
}

// ── Actions ───────────────────────────────────────────────────────────────

async function submit(prompt) {
  if (!prompt.trim() || busy) return;
  $('build-btn').disabled = true;
  try {
    const res = await api('/api/build', { method: 'POST', body: JSON.stringify({ prompt }) });
    if (!res.ok) {
      const body = await res.json().catch(() => ({}));
      toast(body.error || `Request failed (${res.status})`, true);
      $('build-btn').disabled = false;
    }
  } catch (err) {
    toast(`Could not reach the daemon: ${err.message}`, true);
    $('build-btn').disabled = false;
  }
}

$('build-form').addEventListener('submit', (e) => {
  e.preventDefault();
  submit($('prompt').value);
});

$('hint').addEventListener('click', (e) => {
  const chip = e.target.closest('[data-fill]');
  if (!chip) return;
  $('prompt').value = chip.dataset.fill;
  $('prompt').focus();
});

$('undo-btn').addEventListener('click', async () => {
  $('undo-btn').disabled = true;
  const res = await api('/api/undo', { method: 'POST' });
  const body = await res.json();
  toast(body.ok ? `Restored ${fmt(body.blocks)} blocks` : body.error || 'Undo failed', !body.ok);
});

$('cancel-btn').addEventListener('click', async () => {
  await api('/api/cancel', { method: 'POST' });
  toast('Cancelling…');
});

// ── Live updates ──────────────────────────────────────────────────────────

function connect() {
  const url = `/api/events${TOKEN ? `?token=${encodeURIComponent(TOKEN)}` : ''}`;
  const es = new EventSource(url);

  es.addEventListener('state', (e) => {
    const state = JSON.parse(e.data);
    lastState = { ...lastState, ...state };
    renderLive(lastState);
    renderHistory(lastState);
    if (state.status) renderPills(lastState);
  });

  es.addEventListener('log', (e) => addLog(JSON.parse(e.data)));

  es.addEventListener('finished', (e) => {
    const job = JSON.parse(e.data);
    if (job.previewSvg) showPreview(job.previewSvg);
    if (job.status === 'done') toast(`Built ${fmt(job.blocks)} blocks`);
    else if (job.error) toast(job.error, true);
    $('prompt').value = '';
  });

  es.onerror = () => { /* EventSource retries by itself */ };
}

async function refreshStatus() {
  try {
    const res = await api('/api/state');
    if (!res.ok) return;
    const state = await res.json();
    lastState = state;
    $('version').textContent = state.version ? `v${state.version}` : '';
    renderPills(state);
    renderLive(state);
    renderHistory(state);
    if (state.style) $('style').value = state.style;
  } catch { /* the daemon may still be starting */ }
}

function toast(msg, isError = false) {
  const el = document.createElement('div');
  el.className = `toast${isError ? ' error' : ''}`;
  el.textContent = msg;
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 4000);
}

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ));
}
const escapeAttr = escapeHtml;

// ── Boot ──────────────────────────────────────────────────────────────────

(async () => {
  await refreshStatus();
  await Promise.all([renderLibrary(), renderStyles()]);
  const res = await api('/api/logs').catch(() => null);
  if (res?.ok) {
    const { logs } = await res.json();
    for (const l of logs.slice(-40)) addLog(l);
  }
  connect();
  // Status (bot, RCON) is polled: it changes independently of build events.
  setInterval(refreshStatus, 5000);
})();
